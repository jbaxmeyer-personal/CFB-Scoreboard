import type { Team } from '../types/game'

// Full FBS team list for the search-to-add pickers in Settings (favorite /
// protected teams) — independent of whatever teams happen to be on the
// currently-loaded slate. Names + ESPN ids ported from the Dynasty Tracker
// project's vetted schools list. `id` matches the raw ESPN competitor id
// string (e.g. "194"), same format the live scoreboard data uses, so a team
// picked here matches correctly against real games.
//
// Abbreviations are hand-set to match ESPN's own convention (not derived
// from the name) — a handful of newer FBS transitions (Missouri State,
// Kennesaw State, Sam Houston, Jacksonville State) are best-effort since
// this session couldn't verify them against a live ESPN response.
const logo = (espnId: number) => `https://a.espncdn.com/i/teamlogos/ncaa/500/${espnId}.png`

function t(espnId: number, name: string, abbreviation: string, color?: string): Team {
  return {
    id: String(espnId),
    name,
    shortName: name,
    abbreviation,
    color,
    logoLight: logo(espnId),
  }
}

